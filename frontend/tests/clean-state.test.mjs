import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
const directory = new URL('../public/admin-reference/js/', import.meta.url);
const data = await readFile(new URL('data.js', directory),'utf8');
const bridge = await readFile(new URL('api_bridge.js', directory),'utf8');
const dom = new JSDOM('<!doctype html><html><body></body></html>', { url:'http://127.0.0.1/', runScripts:'outside-only' });
const w=dom.window;
let fail=false;
let missingParts=false;
w.fetch=async (path)=>{
 if(missingParts && path.endsWith('/parts'))return new Response(JSON.stringify({error:{code:'api_not_found',message:'missing route'}}),{status:404});
 if(fail) return new Response(JSON.stringify({error:{code:'forbidden',message:'test permission error'}}),{status:403});
 let payload={items:[],total:0,page:1,pageSize:100};
 if(path.endsWith('/auth/me'))payload={user:{id:'admin',username:'admin',displayName:'初期管理者',role:'admin'},csrfToken:'test-only'};
 if(path.endsWith('/health'))payload={database:{driver:'postgres'}};
 if(path.endsWith('/company'))payload={companyName:'新規環境（未設定）',bankAccounts:[]};
 if(path.includes('/users?'))payload={items:[{id:'admin',username:'admin',displayName:'初期管理者',role:'admin',isActive:true}]};
 return new Response(JSON.stringify(payload),{status:200});
};
w.eval(data+'\nwindow.APP_DATA = APP_DATA;');w.eval(bridge);
assert.equal(w.eval('APP_DATA.inventory.length'),0,'fixtures must be cleared before first request');
assert.equal(w.eval('APP_DATA.guestAccounts.length'),0);
assert.equal(w.eval('APP_DATA.boxes.length'),0);
assert.equal(w.eval('Object.keys(APP_DATA.companyInfo).length'),0);
await w.ZaikoAPI.hydrateAdmin();
for(const key of ['inventory','purchaseSlips','sales','shipments','parts','brandRecords','materials','buyers','suppliers','boxes','fxRateHistory','notifications','approvalRequests']) assert.equal(w.eval(`APP_DATA.${key}.length`),key==='boxes'?10:0,key);
assert.ok(w.eval('APP_DATA.fxRates.every(item => item.rate === null)'));
assert.ok(Number.isNaN(w.ZaikoAPI.currentRate('USD')));
assert.equal(w.ZaikoAPI.currentRate('JPY'),1);
assert.equal(w.eval('APP_DATA.companyInfo.bankName'),'');
missingParts=true;
await assert.rejects(w.ZaikoAPI.hydrateAdmin(), 'missing required PostgreSQL endpoints must not be hidden');
missingParts=false;
w.eval('APP_DATA.inventory = [{code:"retained-complete-snapshot"}]');
fail=true;
await assert.rejects(w.ZaikoAPI.hydrateAdmin());
assert.ok(w.ZaikoAPI.state.lastError,'API errors must remain visible');
assert.equal(w.eval('APP_DATA.inventory[0].code'),'retained-complete-snapshot','refresh failure must retain previous complete snapshot');
dom.window.close();
console.log('Clean connected state: empty masters, no fixture restoration, unset rates, and explicit API failure verified.');
