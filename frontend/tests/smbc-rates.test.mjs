import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';

const source = await readFile(new URL('../public/admin-reference/js/app.js', import.meta.url),'utf8');
const dom = new JSDOM('<!doctype html><div id="rates"></div>', {runScripts:'outside-only'});
const w=dom.window;
w.APP_DATA={fxRateSync:{enabled:true,state:{publishedDate:'2026-10-15',lastSuccessAt:'2026-10-15T03:00:00Z'}},fxRates:[{code:'USD',symbol:'$',flag:'',name:'USドル',rate:157.99,updatedAt:'2026/10/15',updatedBy:'SMBC TTM',publishedDate:'2026-10-15'}],fxRateHistory:[],purchaseSlips:[]};
w._escHtml=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
w._renderFxRateTrendCharts=()=>'';
w.isAdmin=()=>true;
w.eval(source.slice(source.indexOf('function renderFxRateTab(area) {'),source.indexOf('// レートをリアルタイムプレビュー')));
const area=w.document.getElementById('rates');
w.renderFxRateTab(area);
assert.match(area.textContent,/157.99/);
assert.match(area.textContent,/1％以上/);
assert.match(area.textContent,/2026-10-15/);
assert.equal(area.querySelectorAll('.fx-rate-input').length,0);
assert.equal(area.querySelectorAll('#smbc-rate-status button').length,1);
w.isAdmin=()=>false;
w.APP_DATA.fxRateSync.state.lastError='<img src=x onerror=alert(1)>取得失敗';
w.renderFxRateTab(area);
assert.equal(area.querySelectorAll('#smbc-rate-status button').length,0);
assert.equal(area.querySelectorAll('[role=alert] img').length,0);
assert.match(area.querySelector('[role=alert]').textContent,/取得失敗/);
w.APP_DATA.fxRateSync.enabled=false;
w.renderFxRateTab(area);
assert.equal(area.querySelectorAll('.fx-rate-input').length,1);
assert.equal(area.querySelectorAll('#smbc-rate-status').length,0);
dom.window.close();
console.log('SMBC rate UI: automatic/manual modes, admin button, source dates, alerts and escaping passed.');
